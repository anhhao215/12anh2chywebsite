  // Tự thêm dấu / sau ngày và sau tháng; vẫn cho phép tự gõ / . - hoặc khoảng trắng
  function formatDob(raw) {
    const caps = [2, 2, 4]
    let out = '', seg = 0, count = 0
    for (const ch of raw) {
      if (/\d/.test(ch)) {
        if (count === caps[seg]) {
          if (seg === 2) break
          out += '/'
          seg++
          count = 0
        }
        out += ch
        count++
      } else if (/[\/.\-\s]/.test(ch) && count > 0 && seg < 2) {
        out += '/'
        seg++
        count = 0
      }
    }
    return out
  }
