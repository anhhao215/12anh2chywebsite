  function startMusic(cfg) {
    stopMusic()
    audioCfg = cfg
    if (!cfg) return
    const a = new Audio()
    audio = a
    a.preload = 'auto'
    a.src = cfg.src
    a.volume = 0
    a.addEventListener('loadedmetadata', () => { if (cfg.start > 0) { try { a.currentTime = cfg.start } catch (_) {} } }, { once: true })
    a.addEventListener('error', () => { console.warn('Không mở được file nhạc: ' + cfg.src); musicBtn.hidden = true; stopMusic() })
    audioOn = true
    setMusicLabel()
    const pr = a.play()
    if (pr && pr.catch) pr.catch(() => { if (audio === a) { audioOn = false; setMusicLabel(); clearInterval(audioTimer) } })
    audioTimer = setInterval(() => {
      const t = Math.max(0, a.currentTime - cfg.start)
      if (a.ended || t >= cfg.dur) { stopMusic(); return }
      a.volume = Math.max(0, Math.min(1, t / 1.2, (cfg.dur - t) / 2)) * .9
    }, 50)
  }
